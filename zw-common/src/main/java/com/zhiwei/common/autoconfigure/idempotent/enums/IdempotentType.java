package com.zhiwei.common.autoconfigure.idempotent.enums;

/**
 * 幂等控制的两种模式
 **/
public enum IdempotentType {

    /**
     * 幂等键模式：由注解上的 key（支持 SPEL）自行推导唯一标识。
     * <p>适合"同一组业务参数只允许处理一次"的场景，例如：同一用户对同一张券只能领取一次。
     * <p>不依赖客户端配合，服务端自证。
     */
    PARAM,

    /**
     * 令牌模式：客户端先向服务端申请一次性令牌，提交时通过请求头携带，服务端原子消费。
     * <p>适合"用户手动点击"的场景，例如：下单、支付等表单提交，防止用户连点、网络重试造成的重复提交。
     * <p>需要客户端配合（先取令牌再提交），但能覆盖"参数不同但语义相同"的重复提交。
     */
    TOKEN
}
